#!/usr/bin/env node
/**
 * Font subsets for LCP (UX-AUDIT-7 R3 — PROPOSED derived performance assets, no identity change): `unicode-range` pieces cut from the
 * package's own complete files (brand/fonts/*.woff2, fpt-brand v1.2.1, SIL OFL 1.1 — subsetting and self-hosting are permitted by the
 * licence; the reserved font names are unchanged in the `name` table) with fontTools `pyftsubset`. Pieces: `arabic` (Arabic blocks + Basic Latin +
 * Latin-1 + general punctuation — the Arabic pages resolve every glyph from one file), `latin` (the Google Fonts «latin» range) and
 * `latin-ext` (the Google Fonts «latin-ext» range — French / Spanish / Portuguese / Turkish letters). Only the weights the site uses are cut.
 * Output: public/fonts/<Family-weight>.<piece>.<sha8>.woff2 + public/fonts/SUBSETS.json (source sha256 of every package file used, output
 * sha256 and byte sizes, ranges, tool version) + src/fonts.generated.css (the @font-face rules with unicode-range, imported by src/fonts.css).
 *   node scripts/build-font-subsets.mjs           # (re)build — deterministic: the same package bytes give the same output bytes
 *   node scripts/build-font-subsets.mjs --check   # fail when the served files differ from a fresh cut (runs in "npm run check")
 * Proposal for the package (report § PROPOSED): move this script and the SUBSETS manifest into fpt-brand as `brand/fonts/subset/`.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const SRC = path.join(ROOT, 'brand', 'fonts');
const OUT = path.join(ROOT, 'public', 'fonts');
const CSS = path.join(ROOT, 'src', 'fonts.generated.css');
const CHECK = process.argv.includes('--check');

const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const LATIN_EXT = 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF';
const ARABIC = 'U+0000-00FF,U+0600-06FF,U+0750-077F,U+08A0-08FF,U+FB50-FDFF,U+FE70-FEFF,U+2000-206F,U+20AC,U+2212,U+FEFF,U+FFFD';
/** family → file stem, the weights the site uses, the pieces to cut. */
export const FONTS = [
  { family: 'IBM Plex Sans Arabic', file: 'IBMPlexSansArabic', weights: [400, 600], pieces: { arabic: ARABIC } },
  { family: 'Inter', file: 'Inter', weights: [400, 600], pieces: { latin: LATIN, 'latin-ext': LATIN_EXT } },
  { family: 'Barlow Condensed', file: 'BarlowCondensed', weights: [700, 800], pieces: { latin: LATIN, 'latin-ext': LATIN_EXT } },
  { family: 'IBM Plex Mono', file: 'IBMPlexMono', weights: [400, 600], pieces: { latin: LATIN, 'latin-ext': LATIN_EXT } },
];

const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');
const tool = execFileSync('pyftsubset', ['--help']).toString().match(/fontTools \S+/)?.[0] ?? 'fonttools';
const tmp = mkdtempSync(path.join(tmpdir(), 'fpt-subset-'));
const manifest = { generatedBy: 'scripts/build-font-subsets.mjs', package: 'fpt-brand v1.2.1 (brand/fonts — complete OFL files)', tool, status: 'PROPOSED — derived performance assets (unicode-range pieces of the package files); identity unchanged', sources: {}, files: [] };
let drift = 0;
for (const f of FONTS) for (const w of f.weights) {
  const input = path.join(SRC, `${f.file}-${w}.woff2`);
  if (!existsSync(input)) throw new Error(`missing package file ${input}`);
  manifest.sources[`${f.file}-${w}.woff2`] = { sha256: sha(input), bytes: readFileSync(input).byteLength };
  for (const [piece, range] of Object.entries(f.pieces)) {
    const built = path.join(tmp, `${f.file}-${w}.${piece}.woff2`);
    execFileSync('pyftsubset', [input, `--unicodes=${range}`, '--flavor=woff2', '--layout-features=*', '--no-hinting', '--desubroutinize', '--name-IDs=*', '--notdef-outline', `--output-file=${built}`], { stdio: 'pipe' });
    const h = sha(built); const served = `${f.file}-${w}.${piece}.${h.slice(0, 8)}.woff2`;
    const target = path.join(OUT, served);
    if (CHECK) { if (!existsSync(target) || sha(target) !== h) { console.error(`[subsets] DRIFT ${served}`); drift++; } }
    else { mkdirSync(OUT, { recursive: true }); writeFileSync(target, readFileSync(built)); }
    manifest.files.push({ family: f.family, weight: w, piece, file: served, url: `/fonts/${served}`, bytes: readFileSync(built).byteLength, sourceBytes: readFileSync(input).byteLength, source: `${f.file}-${w}.woff2`, sha256: h, unicodeRange: range });
  }
}
rmSync(tmp, { recursive: true, force: true });
const css = ['/* GENERATED by scripts/build-font-subsets.mjs — do not edit. unicode-range pieces cut from the fpt-brand v1.2.1 package files (brand/fonts, OFL);',
  '   manifest + source sha256: public/fonts/SUBSETS.json. PROPOSED derived performance assets — the identity (families, weights, metrics) is unchanged. */'];
for (const x of manifest.files) css.push(`@font-face{font-family:'${x.family}';font-style:normal;font-weight:${x.weight};font-display:swap;src:url(${x.url}) format('woff2');unicode-range:${x.unicodeRange}}`);
if (CHECK) {
  const current = readFileSync(CSS, 'utf8');
  if (current !== css.join('\n') + '\n') { console.error('[subsets] DRIFT src/fonts.generated.css'); drift++; }
  const m = JSON.parse(readFileSync(path.join(OUT, 'SUBSETS.json'), 'utf8'));
  for (const x of manifest.files) if (!m.files.some((y) => y.file === x.file && y.sha256 === x.sha256)) { console.error(`[subsets] DRIFT SUBSETS.json: ${x.file}`); drift++; }
  for (const [k, v] of Object.entries(manifest.sources)) if (m.sources[k]?.sha256 !== v.sha256) { console.error(`[subsets] DRIFT source ${k}`); drift++; }
  if (drift) { console.error(`check-font-subsets: FAIL (${drift}) — run node scripts/build-font-subsets.mjs`); process.exit(1); }
  console.log(`check-font-subsets: PASS (${manifest.files.length} pieces under public/fonts = a fresh cut of the package files; SUBSETS.json sources match brand/fonts)`);
} else {
  writeFileSync(path.join(OUT, 'SUBSETS.json'), JSON.stringify(manifest, null, 2) + '\n');
  for (const stale of readdirSync(OUT)) if (/\.woff2$/.test(stale) && !manifest.files.some((x) => x.file === stale)) rmSync(path.join(OUT, stale));
  writeFileSync(CSS, css.join('\n') + '\n');
  for (const x of manifest.files) console.log(`${x.file.padEnd(52)} ${String(x.sourceBytes).padStart(7)} → ${String(x.bytes).padStart(6)} B`);
  console.log(`total ${manifest.files.reduce((n, x) => n + x.bytes, 0)} B over ${manifest.files.length} pieces`);
}
